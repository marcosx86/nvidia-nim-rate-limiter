import asyncio
import os
import time

import httpx
from fastapi import FastAPI, Request
from fastapi.responses import Response

app = FastAPI()

NVIDIA_API_KEY = os.environ["NVIDIA_API_KEY"]

UPSTREAM = "https://integrate.api.nvidia.com"

# Hard limit: 6 requests / 60 seconds.
REQUESTS_PER_MINUTE = 6
WINDOW_SECONDS = 60.0

# Serialize requests. This is particularly useful with NIM quotas.
lock = asyncio.Lock()
request_times: list[float] = []

client = httpx.AsyncClient(
    base_url=UPSTREAM,
    timeout=httpx.Timeout(
        connect=10.0,
        read=300.0,
        write=300.0,
        pool=300.0,
    ),
)


async def acquire_slot():
    global request_times

    while True:
        async with lock:
            now = time.monotonic()

            request_times = [
                t for t in request_times
                if now - t < WINDOW_SECONDS
            ]

            if len(request_times) < REQUESTS_PER_MINUTE:
                request_times.append(now)
                return

            wait_for = WINDOW_SECONDS - (now - request_times[0])

        await asyncio.sleep(wait_for)


@app.api_route(
    "/{path:path}",
    methods=[
        "GET",
        "POST",
        "PUT",
        "PATCH",
        "DELETE",
        "OPTIONS",
        "HEAD",
    ],
)
async def proxy(path: str, request: Request):
    await acquire_slot()

    body = await request.body()

    headers = dict(request.headers)

    # Never forward the client's Authorization header.
    headers.pop("authorization", None)

    # The limiter owns the real NVIDIA credential.
    headers["Authorization"] = f"Bearer {NVIDIA_API_KEY}"

    # These should be generated by the upstream connection.
    headers.pop("host", None)
    headers.pop("content-length", None)

    upstream_path = "/" + path

    if request.url.query:
        upstream_path += "?" + request.url.query

    upstream_response = await client.request(
        request.method,
        upstream_path,
        headers=headers,
        content=body,
    )

    response_headers = dict(upstream_response.headers)

    # Don't expose hop-by-hop headers.
    for h in (
        "content-length",
        "transfer-encoding",
        "connection",
    ):
        response_headers.pop(h, None)

    return Response(
        content=upstream_response.content,
        status_code=upstream_response.status_code,
        headers=response_headers,
        media_type=upstream_response.headers.get("content-type"),
    )
